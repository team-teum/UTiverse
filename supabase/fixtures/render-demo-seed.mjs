import { createHash } from "node:crypto";
import { exampleProfiles } from "../../web/src/api/sandboxExamples.ts";

const batch = "sandbox-neighbors";
const epoch = Date.parse("2026-11-20T00:00:00Z");
const date = (days, order) =>
	new Date(epoch - days * 86_400_000 + order * 60_000).toISOString();
const quoted = (value) =>
	value === null ? "null" : `'${value.replaceAll("'", "''")}'`;
const row = (...values) => `  (${values.map(quoted).join(", ")})`;
const ids = new Map(exampleProfiles.map(({ key, id }) => [key, id]));
const commentId = (star, index) => {
	const hex = createHash("sha256")
		.update(`${batch}:${star}:${index}`)
		.digest("hex");
	return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-8${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
};
const profiles = [],
	stars = [],
	comments = [],
	reactions = [];
for (const profile of exampleProfiles) {
	profiles.push(
		row(
			profile.id,
			profile.nickname,
			profile.tagline,
			JSON.stringify(profile.look),
			batch,
		),
	);
	const reactors = exampleProfiles.filter(({ id }) => id !== profile.id);
	profile.stars.forEach((star, index) => {
		const id = `${profile.id.slice(0, -4)}${String(index + 1).padStart(4, "0")}`;
		stars.push(row(id, profile.id, star.body, date(star.daysAgo, index)));
		let lastOther = null;
		star.comments?.forEach((comment, order) => {
			const author = ids.get(comment.by);
			if (!author) throw new Error(`Unknown demo author: ${comment.by}`);
			const cid = commentId(id, order);
			comments.push(
				row(
					cid,
					id,
					author,
					author === profile.id ? lastOther : null,
					comment.body,
					date(comment.daysAgo, order),
				),
			);
			if (author !== profile.id) lastOther = cid;
		});
		for (const [kind, count] of Object.entries(star.reactions ?? {})) {
			for (const reactor of reactors.slice(0, count))
				reactions.push(row(id, reactor.id, kind));
		}
	});
}

console.log(
	`-- Generated by: node supabase/fixtures/render-demo-seed.mjs\n-- Local or explicitly approved imports only. No Auth users.\nbegin;\nset local standard_conforming_strings = on;`,
);
for (const [table, columns, rows] of [
	["profiles", "id, nickname, tagline, look, demo_batch", profiles],
	["stars", "id, profile_id, body, created_at", stars],
	[
		"comments",
		"id, star_id, profile_id, parent_id, body, created_at",
		comments,
	],
	["reactions", "star_id, profile_id, kind", reactions],
]) {
	if (rows.length)
		console.log(
			`\ninsert into public.${table} (${columns}) values\n${rows.join(",\n")}\non conflict do nothing;`,
		);
}
console.log("\ncommit;");
