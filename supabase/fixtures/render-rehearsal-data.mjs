import { sandboxEvents } from "../../web/src/api/sandboxEvents.ts";
import { exampleLocations } from "../../web/src/api/sandboxExamples.ts";
import { REGIONS } from "../../web/src/lib/regions.ts";

const json = (value) =>
	`'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
if (process.argv[2] === "regions") {
	console.log(`insert into private.valid_regions(sido, sigungu)
select region.sido, sub.name from jsonb_each(${json(REGIONS)}) as region(sido, districts)
cross join lateral jsonb_array_elements_text(region.districts) as sub(name);`);
} else {
	const locations = Object.entries(exampleLocations).map(
		([profile_id, location]) => ({ profile_id, ...location }),
	);
	const events = sandboxEvents.map(({ endDate, isExample, ...event }) => ({
		...event,
		end_date: endDate,
		is_example: isExample,
	}));
	console.log(`-- Local-only calendar and fictional locations. Generated by render-rehearsal-data.mjs.
begin;
set local standard_conforming_strings = on;
insert into public.events select * from jsonb_populate_recordset(null::public.events, ${json(events)}) on conflict do nothing;
insert into private.profile_locations(profile_id, sido, sigungu, visible)
select x.profile_id, x.sido, x.sigungu, x.visible
from jsonb_to_recordset(${json(locations)}) as x(profile_id uuid, sido text, sigungu text, visible boolean)
join public.profiles p on p.id = x.profile_id and p.demo_batch = 'sandbox-neighbors'
on conflict do nothing;
commit;`);
}
